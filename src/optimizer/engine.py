@dataclass
class TestPrompt:
    """A test prompt from CyberSecEval or similar dataset."""

    prompt: str
    """The code generation prompt."""

    language: str
    """Target programming language."""

    cwe_id: str | None = None
    """Associated CWE identifier (if known)."""

    metadata: dict[str, Any] = field(default_factory=dict)
    """Additional metadata."""


@dataclass
class EvaluationResult:
    """Result of evaluating a rule variant on a single prompt."""

    prompt: TestPrompt
    """The test prompt used."""

    generated_code: str
    """Code generated by the LLM."""

    fitness: FitnessResult
    """Fitness calculated from Semgrep analysis."""

    generation_latency_ms: float = 0.0
    """Time to generate code (ms)."""

    analysis_latency_ms: float = 0.0
    """Time to run Semgrep analysis (ms)."""

    input_tokens: int = 0
    """Input tokens billed for the LLM call (0 if backend did not report or
    if this result was served from the eval cache)."""

    output_tokens: int = 0
    """Output tokens generated by the LLM (0 if backend did not report or if
    this result was served from the eval cache)."""


@dataclass
class SearchConfig:
    """Configuration for one search run (EA or random search)."""

    max_iterations: int = 20
    """Maximum number of candidate evaluations. Identity/no-op proposals are
    logged and retried at the same index; they do not consume this budget. EA
    init + injection evaluations do count, so both arms compare equal numbers
    of scored candidates."""

    fitness_strategy: FitnessStrategy = FitnessStrategy.SEVERITY_WEIGHTED
    """How to calculate fitness from Semgrep results."""

    objective_direction: str = "minimize"
    """Optimization direction for the f1 (semgrep_delta) objective.
        "minimize" — reward FEWER vulnerabilities than baseline (REPAIR — the
                     thesis direction and default). Implemented by negating
                     semgrep_delta so the archive's maximize logic is unchanged;
                     a positive recorded f1 means the mutation REDUCED vulns.
        "maximize" — reward MORE vulnerabilities (the adversarial direction;
                     kept for secondary experiments only).
    """

    save_intermediate: bool = True
    """Save intermediate results for analysis."""

    output_dir: Path | None = None
    """Directory to save results."""

    verbose: bool = True
    """Print progress information."""

    enable_validation: bool = False
    """Run MutationQualityValidator on each mutation (observational).
    REQUIRED for real runs: the f2 rule-fidelity objective
    is the validator's SBERT similarity; without it f2 degenerates to a
    constant 1.0 (only acceptable for mock/dry-run smokes)."""

    optimizer: str = "ea"
    """Optimizer family. One of:
        "ea"            — (1+1) EA over a full-chromosome Pareto archive, with
                          random initialization + periodic random injection
        "random_search" — i.i.d. random sampler (independent chromosome per
                          iteration, best-of-budget; no archive)
    """

    archive_cap: int = 6
    """EA only: max Pareto archive size. Sweep-tunable."""

    restart_h: int = 8
    """EA only: consecutive non-inserts before stagnation restart. Sweep-tunable."""

    max_depth: int = 4
    """Per-rule stacked-mutation depth cap (mutations from original), enforced
    in both arms and inside the random-chromosome sampler."""

    random_max_changes: int = 10
    """K for the shared random-chromosome sampler: every random sample stacks
    n ∈ [1, K] changes on a copy of its base (supervisor pseudocode:
    ``n_changes = random(1, 10)``). Used by random search and by the EA's
    init/injection phases."""

    ea_n_mutations: int = 1
    """EA local move: max mutators stacked on the chosen gene per move. 1
    (default) = the canonical (1+1) small step; >1 samples a 1..n chain
    (ablation knob)."""

    ea_init_samples: int = 10
    """EA: number of initial iterations that sample independent random
    chromosomes from the origin and offer them to the archive (population-style
    seeding; supervisor design 2026-07-10)."""

    ea_injection_every: int = 10
    """EA: after init, every N-th iteration injects one origin-based random
    chromosome instead of a parent-based move (diversity maintenance). 0 = off."""

    ea_move: str = "local"
    """EA move for the post-init iterations:
        "local"          — mutate ONE gene of the parent (default, main design)
        "random_builder" — apply the random sampler to the archive parent
                           (selection-only ablation; not the main design)."""

    order_move_weight: float = 0.1
    """Probability of a rule-order move: per EA local move, and per change
    inside the random sampler (keeps the operator pool identical across arms)."""

    ea_origin_parent: bool = True
    """EA: whether the origin is a *sampleable* parent for local moves. On
    (default) it always is, so a minimal parsimony-1 single-rule lineage can be
    seeded any time; off restricts local moves to front members. Either way the
    origin still anchors dominance and ``best()``. Ablation knob (A/B the
    minimal-edit anchor)."""

    enable_eval_cache: bool = True
    """Reuse cached (code, Semgrep result) for prompts whose assembled rule
    text is identical to a previously evaluated one.

    Relies on ``temperature=0.0`` (greedy decoding) yielding deterministic
    generation for identical inputs. Keyed on the per-prompt render signature
    (``RuleSetSpace.prompt_signature``): prompts whose rendered rule set is
    unchanged from a prior evaluation reuse the cached code + Semgrep result,
    skipping both LLM generation and Semgrep analysis.

    Disable this only if the pipeline is switched to ``temperature > 0`` or
    if bit-identical GPU determinism is required — in which case the cache's
    correctness no longer holds.
    """


