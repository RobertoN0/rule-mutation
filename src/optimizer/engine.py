@dataclass
class SearchResult:
    """Final result of one search run (EA or random search).

    The best chromosome's identity + objectives live in ``pool_arm_stats``
    (``best_chromosome``) and ``compounding_state`` (the archive snapshot); the
    meaningful "best" here is ``best_fitness``.
    """

    original_fitness: AggregatedFitness
    """Fitness of the origin chromosome (baseline)."""

    best_fitness: AggregatedFitness
    """Fitness of the best chromosome (under minimize: the best repair)."""

    iterations: list[IterationResult]
    """All iteration results."""

    total_time_seconds: float
    """Total optimization time."""

    total_llm_calls: int
    """Total number of LLM API calls."""

    config: SearchConfig
    """Configuration used."""

    pool_arm_stats: dict | None = None
    """Per-strategy mutator/restart stats from the EA / random-search runner."""

    compounding_state: dict | None = None
    """The single chromosome-archive snapshot from the EA runner ({} for random)."""

    eval_cache_stats: dict | None = None
    """Hit/miss counts for the per-prompt generation+Semgrep cache."""

    total_input_tokens: int = 0
    """Cumulative input-token count across all code-generation LLM calls.
    Persisted to the run summary JSON for cost estimation against paid APIs."""

    total_output_tokens: int = 0
    """Cumulative output-token count across all code-generation LLM calls."""

class ExperimentEngine:
    """Runs one search experiment: baseline + evaluation seam + persistence.

    Evaluates the origin chromosome (baseline), then dispatches to the selected
    search algorithm (:func:`search.run_ea` / :func:`search.run_random_search`),
    serving it whole-chromosome evaluations (LLM code generation + Semgrep,
    cached per prompt under temperature=0) and persisting every artifact
    (iterations.jsonl, archive snapshots, mutated rules, run summary).

    """

    # System prompt template for code generation
    SYSTEM_TEMPLATE = (
        "You are a software engineer. Before writing code, carefully review "
        "and follow all of the coding guidelines provided below. "
        "The required implementation language is {language}. If the user prompt "
        "allows a language choice, choose {language}. Return one complete "
        "implementation only; do not include explanations.\n\n"
        "=== CODING GUIDELINES ===\n\n"
        "{rules}"
        "\n=== END GUIDELINES ==="
    )

    # Baseline system prompt (no rules)
    BASELINE_SYSTEM = (
        "You are a software engineer. "
        "The required implementation language is {language}. If the user prompt "
        "allows a language choice, choose {language}. Return one complete "
        "implementation only; do not include explanations."
    )

    def __init__(
        self,
        llm_backend: LLMBackend,
        mutator: "Mutator | MutatorPool",
        config: SearchConfig | None = None,
        validator: MutationQualityValidator | None = None,
    ):
        """Initialize the engine.

        Args:
            llm_backend: LLM backend for code generation.
            mutator: Single mutator or :class:`MutatorPool`.  A single
                mutator is auto-wrapped in a pool.
            config: Search configuration.
            validator: Optional quality validator. When provided and
                ``config.enable_validation`` is True, every changed gene is
                validated observationally (metrics recorded; acceptance is
                never gated) and its SBERT similarity feeds the f2
                rule-fidelity objective.
        """
        self.llm = llm_backend
        self.config = config or SearchConfig()
        self.validator = validator

        # Per-case baseline fitness (populated during run_search baseline run)
        self._baseline_fitness_per_case: dict[str, FitnessResult] = {}
        self._expected_language_per_case: dict[str, str] = {}

        # Wrap single mutator in a pool for uniform handling
        if isinstance(mutator, MutatorPool):
            self.pool = mutator
        else:
            self.pool = MutatorPool([mutator], seed=getattr(mutator, "seed", None))
        # Backward compat: self.mutator points to first mutator in the pool
        self.mutator = self.pool.mutators[0]

        # Tracking
        self._total_llm_calls = 0
        self._total_input_tokens = 0
        self._total_output_tokens = 0

        # Evaluation cache: (tc_id, sha256(rule_text)) -> {code, gen_latency_ms,
        # semgrep_result, analysis_latency_ms}.  Hits skip both code generation
        # and Semgrep analysis for a prompt whose assembled rule text is
        # byte-identical to a previously evaluated input.
        self._eval_cache: dict[tuple[str, str], dict[str, Any]] = {}
        self._eval_cache_hits = 0
        self._eval_cache_misses = 0

        # Per-iter writer state. iterations.jsonl is opened lazily on first
        # write and closed by _close_iterations_writer at end of run.
        self._iterations_jsonl_file: Any | None = None
        self._iterations_jsonl_path: Any | None = None

    def _open_iterations_writer(self) -> None:
        """Open iterations.jsonl for append. No-op if output_dir is None."""
        if self._iterations_jsonl_file is not None:
            return
        output_dir = self.config.output_dir
        if not output_dir:
            return
        from pathlib import Path
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)
        self._iterations_jsonl_path = output_dir / "iterations.jsonl"
        self._iterations_jsonl_file = open(self._iterations_jsonl_path, "a", encoding="utf-8")

    def _append_iteration_record(self, record: dict) -> None:
        """Append a canonical per-iter record to iterations.jsonl.

        Record schema:
            iter, timestamp, strategy, phase, rule_id, mutation_chain,
            chain_length, n_requested_changes, n_attempted_changes,
            n_effective_changes, attempted_operators, attempted_mutators,
            mutation_identity, priority_rule_ids, priority_offset_count,
            f1, f2, f3, f1_advance,
            accepted, llm_calls_total, input_tokens_total, output_tokens_total,
            validation_metadata {rule_id: quality}, selection_meta {...}

        phase: "init" / "injection" / "ea" (EA strategy) or "random".
        selection_meta carries strategy-specific fields:
          - ea:            parent_f1, n_eligible_rules, restarts_this_iter
          - random_search: {} (independent samples — no parent, no restart)
        """
        if self._iterations_jsonl_file is None:
            self._open_iterations_writer()
        if self._iterations_jsonl_file is None:
            return  # no output_dir; silent skip
        if record.get("llm_calls_total") is None:
            record["llm_calls_total"] = self._total_llm_calls
        if record.get("input_tokens_total") is None:
            record["input_tokens_total"] = self._total_input_tokens
        if record.get("output_tokens_total") is None:
            record["output_tokens_total"] = self._total_output_tokens
        fcntl.flock(self._iterations_jsonl_file.fileno(), fcntl.LOCK_EX)
        try:
            self._iterations_jsonl_file.write(json.dumps(record) + "\n")
            self._iterations_jsonl_file.flush()
        finally:
            fcntl.flock(self._iterations_jsonl_file.fileno(), fcntl.LOCK_UN)

    def _close_iterations_writer(self) -> None:
        """Close iterations.jsonl. Safe to call multiple times."""
        if self._iterations_jsonl_file is not None:
            try:
                self._iterations_jsonl_file.close()
            finally:
                self._iterations_jsonl_file = None


    def _save_intermediate_iter_jsonl(
        self,
        iter_id: str,
        results: list[dict],
    ) -> None:
        """Pack one iteration's per-prompt evaluation records into one JSONL.

        Written under <output_dir>/intermediate/{iter_id}.jsonl.
        iter_id examples: "baseline", "ea_iter0001", "rand_iter0042".
        """
        output_dir = self.config.output_dir
        if not output_dir:
            return
        from pathlib import Path
        new_dir = Path(output_dir) / "intermediate"
        new_dir.mkdir(parents=True, exist_ok=True)
        path = new_dir / f"{iter_id}.jsonl"
        with open(path, "w", encoding="utf-8") as f:
            for r in results:
                f.write(json.dumps(r) + "\n")

    def _save_chromosome_move(
        self,
        iteration: int,
        chromo: RuleSetChromosome,
        space: RuleSetSpace,
        move_type: str,
        rule_id: str | None,
        chain_names: list[str],
        changes: list[str],
        validation_metadata: dict | None = None,
        accepted: bool | None = None,
    ) -> None:
        """Write a chromosome's mutated-gene texts + a manifest for one iteration.

        Writes every mutated gene's current allele to
        ``mutated_rules/iterNNN/<rule>.md`` (so a snapshot entry accepted at
        iteration NNN can reference its genes there) plus ``meta.json`` describing
        the move + full chromosome state. Called for every evaluated iteration
        (EA: accepted or rejected; random: every step)."""
        output_dir = self.config.output_dir
        if not output_dir:
            return
        from pathlib import Path
        iter_dir = Path(output_dir) / "mutated_rules" / f"iter{iteration:03d}"
        iter_dir.mkdir(parents=True, exist_ok=True)
        for rid in sorted(chromo.mutated_rule_ids()):
            short = rid.replace("codeguard-", "cg-")
            (iter_dir / f"{short}.md").write_text(space.allele(chromo, rid), encoding="utf-8")
        meta = {
            "iteration": iteration,
            "chromosome_id": chromo.cid,
            "parent_id": chromo.parent_id,
            "move_type": move_type,
            "changed_rule_id": rule_id,
            "chain": list(chain_names),
            "mutated_rule_ids": sorted(chromo.mutated_rule_ids()),
            "order_priority": dict(chromo.order_priority),
            "changes": list(changes),
            "gene_paths": {rid: g.mutation_path for rid, g in chromo.genes.items()},
            "accepted": accepted,
            "validation_metadata": validation_metadata or {},
        }
        (iter_dir / "meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")

    def _log_validation(self, rule_id: str | None, chain_names: list[str], meta: dict) -> None:
        """Compact quality-validation log line (B3): passes_all + failure reason."""
        if not self.config.verbose or not meta:
            return
        v = self.validator
        passes = meta.get("passes_all")
        if passes is False:
            sbert = meta.get("sbert_step")
            ppl = meta.get("perplexity_ratio")
            ic = meta.get("inline_code_retention", 1.0)
            kw = meta.get("keyword_retention", 1.0)
            if not meta.get("instruction_adherent", True):
                reason = "instruction_adherent=False"
            elif sbert is not None and v is not None and sbert < v.sbert_threshold:
                reason = f"sbert_step<thr ({sbert:.2f}<{v.sbert_threshold:.2f})"
            elif ppl is not None and v is not None and ppl > v.perplexity_threshold:
                reason = f"perplexity>thr ({ppl:.2f}>{v.perplexity_threshold:.2f})"
            elif ic < 1.0:
                reason = f"inline_code_retention<1.0 ({ic:.2f})"
            elif v is not None and kw < v.keyword_threshold:
                reason = f"keyword_retention<thr ({kw:.2f}<{v.keyword_threshold:.2f})"
            else:
                reason = "unknown"
        else:
            reason = "passed"
        rule_short = (rule_id or "?").replace("codeguard-", "cg-")
        self._log(
            f"   Validation [rule={rule_short}, mut={'+'.join(chain_names) or '?'}]: "
            f"passes_all={passes} REASON={reason} | "
            f"adherent={meta.get('instruction_adherent')} "
            f"sbert_step={meta.get('sbert_step')} sbert_cum={meta.get('sbert_cum')} "
            f"ppl={meta.get('perplexity_ratio')} "
            f"inline_code={meta.get('inline_code_retention')} "
            f"keywords={meta.get('keyword_retention')}"
        )

    def _save_chromosome_snapshot(self, iteration: int, snap: dict) -> None:
        """Dump the single chromosome-archive snapshot (archive sub-schema 4).

        Written under ``archive_snapshots/iterNNNN.json`` as a list of full
        chromosomes (not per-rule archives). Each gene gets a ``text_ref``
        pointing at ``mutated_rules/iter{iteration_added:03d}/<rule>.md`` (all of
        an entry's genes were written there on accept)."""
        output_dir = self.config.output_dir
        if not output_dir:
            return
        from pathlib import Path
        snap_dir = Path(output_dir) / "archive_snapshots"
        snap_dir.mkdir(parents=True, exist_ok=True)

        def _with_refs(entry: dict) -> dict:
            e = dict(entry)
            it = e.get("iteration_added", 0)
            genes = {}
            for rid, g in (e.get("genes") or {}).items():
                gg = dict(g)
                short = rid.replace("codeguard-", "cg-")
                gg["text_ref"] = f"mutated_rules/iter{it:03d}/{short}.md"
                genes[rid] = gg
            e["genes"] = genes
            return e

        payload = {
            "iter": iteration,
            "schema_version": 4,
            "cap": snap.get("cap"),
            "restart_h": snap.get("restart_h"),
            "origin": snap.get("origin"),
            "n_inserts": snap.get("n_inserts"),
            "n_rejected": snap.get("n_rejected"),
            "n_dup_rejected": snap.get("n_dup_rejected"),
            "n_neutral_inserts": snap.get("n_neutral_inserts"),
            "restart_history": snap.get("restart_history", []),
            "chromosomes": [_with_refs(e) for e in snap.get("entries", [])],
        }
        with open(snap_dir / f"iter{iteration:04d}.json", "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2)

    def _log(self, message: str) -> None:
        """Print if verbose mode enabled."""
        if self.config.verbose:
            print(message)

    def _record_evaluation_failure(
        self,
        *,
        iter_id: str,
        stage: str,
        error_kind: str,
        message: str,
        test_case_id: str | None = None,
        details: dict[str, Any] | None = None,
    ) -> None:
        """Append a structured fatal-evaluation record before propagating it."""
        if not self.config.output_dir:
            return
        path = Path(self.config.output_dir) / "evaluation_failures.jsonl"
        path.parent.mkdir(parents=True, exist_ok=True)
        record = {
            "timestamp": datetime.now().astimezone().isoformat(),
            "iter_id": iter_id,
            "stage": stage,
            "error_kind": error_kind,
            "test_case_id": test_case_id,
            "message": message,
            "details": details or {},
        }
        with path.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(record) + "\n")

    def _build_system_prompt(self, rule_text: str | None, language: str) -> str:
        """Build system prompt with rule injected.

        Args:
            rule_text: Rule text to inject, or None for baseline.

        Returns:
            System prompt string.
        """
        display_language = "Python" if language == "python" else "Java"
        if not rule_text:
            return self.BASELINE_SYSTEM.format(language=display_language)
        return self.SYSTEM_TEMPLATE.format(rules=rule_text, language=display_language)

    def _generate_code(
        self,
        rule_text: str | None,
        prompt: TestPrompt,
    ) -> tuple[str, float, int, int, str]:
        """Generate code using the LLM with given rule.

        Returns:
            Raw code, latency, token counts, and backend finish reason.
        """
        system = self._build_system_prompt(rule_text, prompt.language)
        messages = [{"role": "user", "content": prompt.prompt}]

        response = self.llm.generate(system=system, messages=messages)
        self._total_llm_calls += 1
        self._total_input_tokens += response.input_tokens
        self._total_output_tokens += response.output_tokens

        return (
            response.content,
            response.latency_ms,
            response.input_tokens,
            response.output_tokens,
            getattr(response, "finish_reason", "unknown") or "unknown",
        )



    def run_search(self, prompts_with_rules: list["PromptWithRules"], should_stop_fn: "Callable[[], bool] | None" = None) -> SearchResult:
        """Run the configured search (EA / random search) over per-prompt rule sets.

        Evaluates the origin chromosome as the baseline, then hands the
        evaluation seam to the selected search algorithm. Each prompt renders
        its own retrieved rules from the current chromosome's alleles in the
        chromosome's global order.

        Args:
            prompts_with_rules: Prompts with their associated rules.
            should_stop_fn: Optional graceful-stop predicate checked at the top
                of each optimizer iteration. Returns True when a SLURM
                pre-timeout SIGUSR1 has been received, so the run breaks cleanly
                and finalization (summary, final snapshot) still happens.

        Returns:
            SearchResult with optimization results.
        """
        start_time = time.perf_counter()
        self._total_llm_calls = 0
        self._total_input_tokens = 0
        self._total_output_tokens = 0
        self._baseline_fitness_per_case.clear()
        self._expected_language_per_case.clear()
        if not prompts_with_rules:
            raise ValueError("No prompts were supplied")
        task_ids = [
            str(pwr.metadata.get("test_case_id", f"case_{idx}"))
            for idx, pwr in enumerate(prompts_with_rules)
        ]
        duplicate_ids = sorted({task_id for task_id in task_ids if task_ids.count(task_id) > 1})
        if duplicate_ids:
            raise ValueError(f"Duplicate test_case_id values are not allowed: {duplicate_ids[:3]}")

        self._log(f"Starting per-prompt-rules optimization: {self.config.max_iterations} iterations, "
                  f"{len(prompts_with_rules)} prompts")

        # Log per-prompt rule assignments
        self._log("\nTest case → Rules mapping:")
        for idx, pwr in enumerate(prompts_with_rules):
            tc_id = pwr.metadata.get('test_case_id', f'case_{idx}')
            cwe = pwr.cwe_id or 'unknown'
            lang = pwr.language
            num_rules = len(pwr.rule_ids)

            self._log(f"   [{idx+1}] TC#{tc_id} ({lang}, {cwe}): {num_rules} rules")
            for rule_id in pwr.rule_ids:
                short_name = rule_id.replace('codeguard-', 'cg-').replace('-0-', '0-').replace('-1-', '1-')
                self._log(f"       • {short_name}")

        # Collect all unique rule IDs across prompts, sorted for determinism
        all_rule_ids: list[str] = sorted({rid for pwr in prompts_with_rules for rid in pwr.rule_ids})
        self._log(f"\nUnique rules in experiment ({len(all_rule_ids)} total):")

        for rid in all_rule_ids:
            n_prompts = sum(1 for pwr in prompts_with_rules if rid in pwr.rule_ids)
            short = rid.replace('codeguard-', 'cg-')
            self._log(f"   • {short} — applies to {n_prompts}/{len(prompts_with_rules)} prompts")

        # ── Build the rule-set search space (genome definition) ─────────────
        rule_originals: dict[str, str] = {}
        for pwr in prompts_with_rules:
            for rid, text in pwr.individual_rules.items():
                rule_originals.setdefault(rid, text)
        missing = [rid for rid in all_rule_ids if rid not in rule_originals]
        if missing:
            raise RuntimeError(
                f"{len(missing)} rule(s) missing individual_rules text: {missing[:3]}"
            )
        space = RuleSetSpace(all_rule_ids=list(all_rule_ids), originals=rule_originals)
        origin = space.origin()

        #########################################
        # Evaluate baseline (origin chromosome) #
        #########################################
        self._log("\n📊 Evaluating baseline (origin chromosome)...")
        try:
            original_fitness, original_results, _reused, _rerun = self._evaluate_chromosome(
                origin, space, prompts_with_rules, iter_id="baseline",
            )
        except Exception as e:
            if "rate_limit" in str(e).lower() or "429" in str(e):
                self._log("\n Rate limit hit during baseline evaluation")
            raise

        self._log(f"   Baseline fitness: {original_fitness.total_fitness:.1f} "
                  f"({original_fitness.num_vulnerable}/{original_fitness.num_prompts} vulnerable, "
                  f"{original_fitness.total_raw_count} raw findings, "
                  f"{original_fitness.total_weighted_score:.1f} weighted)")

        original_fitness.total_raw_reduction = 0.0
        original_fitness.total_weighted_reduction = 0.0
        self._save_evaluation_manifest(original_results)

        # Origin objectives (conservative set): (f1=0, fidelity=1.0, −parsimony=0)
        from .search import _objectives
        origin.f1, origin.f2, origin.f3 = _objectives(original_fitness)
        origin.fitness = original_fitness

        if self.config.optimizer not in ("ea", "random_search"):
            raise ValueError(
                f"Unknown optimizer {self.config.optimizer!r}; "
                f"expected 'ea' or 'random_search'"
            )
        return self._run_ea_or_random(
            space=space,
            origin=origin,
            prompts_with_rules=prompts_with_rules,
            original_fitness=original_fitness,
            start_time=start_time,
            should_stop_fn=should_stop_fn,
        )

    def _run_ea_or_random(
        self,
        *,
        space: RuleSetSpace,
        origin: RuleSetChromosome,
        prompts_with_rules: list["PromptWithRules"],  # type: ignore
        original_fitness: AggregatedFitness,
        start_time: float,
        should_stop_fn: "Callable[[], bool] | None" = None,
    ) -> SearchResult:
        """Dispatch to the chromosome EA / random-search runner and map the result
        back into SearchResult so downstream serialisation keeps working."""
        from .search import run_ea, run_random_search

        def evaluate_chromosome_fn(chromo: RuleSetChromosome, iter_id: str):
            return self._evaluate_chromosome(
                chromo, space, prompts_with_rules,
                iter_id=iter_id, should_stop_fn=should_stop_fn,
            )

        def save_move_fn(*, iteration, child, space, move_type, rule_id, chain_names,
                         changes, validation_metadata=None, accepted=None):
            self._save_chromosome_move(
                iteration, child, space, move_type, rule_id, chain_names, changes,
                validation_metadata=validation_metadata, accepted=accepted,
            )

        def validate_move_fn(rule_id, parent_text, mutated_text, chain_names, changes):
            """Run the quality validator on one mutation (observational — never
            refuses). Returns the quality dict (+ cumulative SBERT vs the original
            rule) or {} when validation is disabled."""
            if self.validator is None or not self.config.enable_validation:
                return {}
            from ..mutation.base import MutationResult
            mr = MutationResult(original=parent_text, mutated=mutated_text,
                                mutation_type="+".join(chain_names) or "chromosome_move",
                                changes=list(changes))
            self.validator.validate(mr)
            meta = dict(mr.metadata.get("quality", {}))
            original_text = space.originals.get(rule_id)
            if original_text is not None:
                orig_prose = self.validator._extract_prose_text(original_text)
                cand_prose = self.validator._extract_prose_text(mutated_text)
                meta["sbert_cum"] = self.validator._compute_sbert_similarity(orig_prose, cand_prose)
            self._log_validation(rule_id, chain_names, meta)
            return meta

        def snapshot_fn(iteration, snap):
            self._save_chromosome_snapshot(iteration, snap)

        seed = self.pool.seed  # share seed with the mutator pool for reproducibility

        self._open_iterations_writer()
        try:
            if self.config.optimizer == "ea":
                run_result = run_ea(
                    space=space, origin=origin,
                    prompts_with_rules=prompts_with_rules,
                    mutators=self.pool.mutators,
                    evaluate_chromosome_fn=evaluate_chromosome_fn,
                    iteration_result_factory=IterationResult,
                    max_iterations=self.config.max_iterations,
                    archive_cap=self.config.archive_cap,
                    restart_h=self.config.restart_h,
                    max_depth=self.config.max_depth,
                    ea_n_mutations=self.config.ea_n_mutations,
                    ea_move=self.config.ea_move,
                    init_random_samples=self.config.ea_init_samples,
                    random_injection_every=self.config.ea_injection_every,
                    random_max_changes=self.config.random_max_changes,
                    order_move_weight=self.config.order_move_weight,
                    ea_origin_parent=self.config.ea_origin_parent,
                    seed=seed, log=self._log,
                    iter_record_fn=self._append_iteration_record,
                    archive_snapshot_fn=snapshot_fn,
                    save_move_fn=save_move_fn,
                    validate_move_fn=validate_move_fn,
                    should_stop_fn=should_stop_fn,
                )
            else:  # "random_search"
                run_result = run_random_search(
                    space=space, origin=origin,
                    prompts_with_rules=prompts_with_rules,
                    mutators=self.pool.mutators,
                    evaluate_chromosome_fn=evaluate_chromosome_fn,
                    iteration_result_factory=IterationResult,
                    max_iterations=self.config.max_iterations,
                    max_changes=self.config.random_max_changes,
                    max_depth=self.config.max_depth,
                    order_move_prob=self.config.order_move_weight,
                    seed=seed, log=self._log,
                    iter_record_fn=self._append_iteration_record,
                    save_move_fn=save_move_fn,
                    validate_move_fn=validate_move_fn,
                    should_stop_fn=should_stop_fn,
                )
        finally:
            self._close_iterations_writer()

        total_time = time.perf_counter() - start_time
        best = run_result.best_chromosome
        best_fitness = run_result.best_fitness or original_fitness

        self._log(
            f"\n📦 {self.config.optimizer} run complete: "
            f"{len(run_result.iterations)} iterations, best f1={best.f1:+.2f} "
            f"(mutated={sorted(best.mutated_rule_ids())}), {run_result.n_accepted} accepted"
        )

        result = SearchResult(
            original_fitness=original_fitness,
            best_fitness=best_fitness,
            iterations=run_result.iterations,
            total_time_seconds=total_time,
            total_llm_calls=self._total_llm_calls,
            total_input_tokens=self._total_input_tokens,
            total_output_tokens=self._total_output_tokens,
            config=self.config,
            pool_arm_stats={
                "strategy": self.config.optimizer,
                "mutator_stats": run_result.mutator_stats,
                **(
                    {"restart_reason_counts": run_result.restart_reason_counts}
                    if self.config.optimizer == "ea" else {}
                ),
                "best_chromosome": {
                    "chromosome_id": best.cid,
                    "evaluation_iteration": best.evaluation_iteration,
                    "mutated_rule_ids": sorted(best.mutated_rule_ids()),
                    "order_priority": dict(best.order_priority),
                    "f1": best.f1, "f2": best.f2, "f3": best.f3,
                },
            },
            compounding_state=run_result.archive_snapshot,  # single chromosome archive
            eval_cache_stats={
                "enabled": self.config.enable_eval_cache,
                "hits": self._eval_cache_hits,
                "misses": self._eval_cache_misses,
                "total_entries": len(self._eval_cache),
            },
        )

        if self.config.save_intermediate and self.config.output_dir:
            self._save_results(result)

        return result



    # ==================================================================
    # Chromosome evaluation seam (pure render → score; no mutation, no
    # archive, no mutated-rule-file writes — those live in the runner).
    # ==================================================================

    def _chromosome_fidelity(self, chromo: RuleSetChromosome, space: RuleSetSpace) -> float:
        """Mean SBERT similarity of each MUTATED rule's current text vs its original.

        1.0 when nothing is mutated. Uses the same prose-extraction + SBERT path as
        the per-move ``sbert_cum`` so the objective is consistent with the validation
        numbers. Returns 1.0 if the validator is absent — real runs enforce
        ``enable_validation`` upstream (mock/dry-run smokes may omit it, degenerating
        f2 to a constant).
        """
        mutated = chromo.mutated_rule_ids()
        if not mutated or self.validator is None:
            return 1.0
        sims: list[float] = []
        for rid in sorted(mutated):
            orig = space.originals.get(rid)
            if orig is None:
                continue
            orig_prose = self.validator._extract_prose_text(orig)
            cand_prose = self.validator._extract_prose_text(space.allele(chromo, rid))
            sims.append(self.validator._compute_sbert_similarity(orig_prose, cand_prose)) # type: ignore
        return sum(sims) / len(sims) if sims else 1.0

    def _evaluate_chromosome(
        self,
        chromo: RuleSetChromosome,
        space: RuleSetSpace,
        prompts_with_rules: list["PromptWithRules"],  # type: ignore
        *,
        iter_id: str,
        should_stop_fn: "Callable[[], bool] | None" = None,
        baseline_evaluation: bool | None = None,
    ) -> tuple[AggregatedFitness, list[EvaluationResult], int, int]:
        """Render every prompt from ``chromo`` and score the whole chromosome.

        For each prompt the rule block is rendered from the chromosome's alleles
        in the chromosome's global order (``space.render_prompt``); the eval cache
        is keyed on ``(tc_id, space.prompt_signature(...))`` so prompts whose
        rendered rule set is unchanged from a prior evaluation reuse the cached
        (code, Semgrep) result. Objectives are aggregated over the whole chromosome.

        Returns ``(aggregated_fitness, per_prompt_results, n_reused, n_rerun)``.
        """
        mutated = chromo.mutated_rule_ids()
        cache_enabled = self.config.enable_eval_cache
        is_baseline = iter_id == "baseline" if baseline_evaluation is None else baseline_evaluation

        if is_baseline:
            unsupported = []
            for idx, pwr in enumerate(prompts_with_rules):
                expected = normalize_language(pwr.language)
                if expected not in SUPPORTED_ANALYSIS_LANGUAGES:
                    tc_id = str(pwr.metadata.get("test_case_id", f"case_{idx}"))
                    unsupported.append(f"TC#{tc_id}: {expected!r}")
            if unsupported:
                message = (
                    "Baseline configuration contains unsupported map languages; "
                    "no model calls were made: " + ", ".join(unsupported[:10])
                )
                self._record_evaluation_failure(
                    iter_id=iter_id,
                    stage="baseline_configuration",
                    error_kind="unsupported_map_language",
                    message=message,
                )
                raise BaselineOutputError(message)

        generated: list[_GeneratedSample] = []
        semgrep_results: list[Any] = [None] * len(prompts_with_rules)
        analysis_latency_per_sample: list[float] = [0.0] * len(prompts_with_rules)
        fresh_indices: list[int] = []
        cache_keys: list[tuple[str, str] | None] = [None] * len(prompts_with_rules)
        cache_hit_flags: list[bool | None] = [None] * len(prompts_with_rules)

        # ---- Phase 1: render + generate (cache short-circuits unaffected prompts)
        for idx, pwr in enumerate(prompts_with_rules):
            if not is_baseline and should_stop_fn is not None and should_stop_fn():
                from .search import WallTimeStop
                raise WallTimeStop()

            assembled = space.render_prompt(chromo, pwr.rule_ids)
            rule_text = assembled if assembled else None  # empty ⇒ baseline system prompt
            expected_map_language = normalize_language(pwr.language)
            test_prompt = TestPrompt(
                prompt=pwr.prompt, language=expected_map_language or pwr.language,
                cwe_id=pwr.cwe_id, metadata=dict(pwr.metadata),
            )
            tc_id = pwr.metadata.get("test_case_id", f"case_{idx}")

            cache_hit = None
            if cache_enabled:
                sig = space.prompt_signature(chromo, pwr.rule_ids)
                key = (str(tc_id), sig)
                cache_keys[idx] = key
                cache_hit = self._eval_cache.get(key)

            if cache_hit is not None:
                self._eval_cache_hits += 1
                cache_hit_flags[idx] = True
                generated.append(
                    _GeneratedSample(
                        raw_code=cache_hit["code"],
                        generation_latency_ms=cache_hit["gen_latency_ms"],
                        input_tokens=0,
                        output_tokens=0,
                        finish_reason=cache_hit.get("finish_reason", "unknown"),
                        prompt=test_prompt,
                        prompt_with_rules=pwr,
                    )
                )
                semgrep_results[idx] = cache_hit["semgrep_result"]
                analysis_latency_per_sample[idx] = cache_hit["analysis_latency_ms"]
            else:
                self._eval_cache_misses += 1
                if cache_enabled:
                    cache_hit_flags[idx] = False
                try:
                    code, gen_latency, in_tok, out_tok, finish_reason = self._generate_code(
                        rule_text, test_prompt
                    )
                except Exception as exc:
                    self._record_evaluation_failure(
                        iter_id=iter_id,
                        stage="generation",
                        error_kind=type(exc).__name__,
                        message=str(exc),
                        test_case_id=str(tc_id),
                    )
                    raise
                generated.append(
                    _GeneratedSample(
                        raw_code=code,
                        generation_latency_ms=gen_latency,
                        input_tokens=in_tok,
                        output_tokens=out_tok,
                        finish_reason=finish_reason,
                        prompt=test_prompt,
                        prompt_with_rules=pwr,
                    )
                )
                fresh_indices.append(idx)

        n_total = len(prompts_with_rules)
        n_fresh = len(fresh_indices)
        self._log(f"   🤖 {n_total} prompts: generated {n_fresh}, reused {n_total - n_fresh} from cache")

        # The retrieval map defines the study stratum. Validation never changes
        # the analysis language in response to a model output.
        baseline_failures: list[str] = []
        for idx, sample in enumerate(generated):
            tc_id = str(sample.prompt.metadata.get("test_case_id", f"case_{idx}"))
            if is_baseline:
                expected = normalize_language(sample.prompt.language)
                if expected not in SUPPORTED_ANALYSIS_LANGUAGES:
                    baseline_failures.append(
                        f"TC#{tc_id}: unsupported map language {expected!r}"
                    )
                    continue
                self._expected_language_per_case[tc_id] = expected
            else:
                expected = self._expected_language_per_case.get(tc_id)
                if expected is None:
                    raise RuntimeError(
                        f"No baseline language for TC#{tc_id}; baseline evaluation is required"
                    )

            sample.prompt.language = expected
            try:
                sample.validation = validate_generated_output(
                    sample.raw_code,
                    expected_language=expected,
                    finish_reason=sample.finish_reason,
                )
            except Exception as exc:
                self._record_evaluation_failure(
                    iter_id=iter_id,
                    stage="output_validation",
                    error_kind=type(exc).__name__,
                    message=str(exc),
                    test_case_id=tc_id,
                )
                raise EvaluationInfrastructureError(
                    f"Output validator failure for TC#{tc_id}: {exc}"
                ) from exc
            if is_baseline and not sample.validation.is_valid:
                self._record_evaluation_failure(
                    iter_id=iter_id,
                    stage="baseline_output_validation",
                    error_kind=sample.validation.status,
                    message=sample.validation.failure_reason or "invalid baseline output",
                    test_case_id=tc_id,
                    details={
                        "finish_reason": sample.finish_reason,
                        "input_tokens": sample.input_tokens,
                        "output_tokens": sample.output_tokens,
                        "expected_language": sample.validation.expected_language,
                        "detected_language": sample.validation.detected_language,
                        "syntax_error": sample.validation.syntax_error,
                        "generated_code": sample.raw_code,
                        "analyzed_code_sha256": hashlib.sha256(
                            sample.validation.code.encode("utf-8")
                        ).hexdigest(),
                    },
                )
                baseline_failures.append(
                    f"TC#{tc_id}: {sample.validation.status} "
                    f"({sample.validation.failure_reason})"
                )

        if baseline_failures:
            failure_message = (
                "Baseline preflight failed; no candidate scores were produced:\n"
                + "\n".join(baseline_failures[:10])
            )
            self._record_evaluation_failure(
                iter_id=iter_id,
                stage="baseline_preflight",
                error_kind="invalid_baseline_output",
                message=failure_message,
            )
            raise BaselineOutputError(
                failure_message
            )

        # ---- Phase 2: batch Semgrep on fresh (cache-missed) samples only
        if fresh_indices:
            self._log(
                f"   ⚡ Running Semgrep batch on {len(fresh_indices)} samples "
                f"({len(generated) - len(fresh_indices)} reused from cache)..."
            )
            fresh_samples = []
            for i in fresh_indices:
                sample = generated[i]
                validation = sample.validation
                if validation is None:
                    raise RuntimeError(f"Missing output validation for prompt index {i}")
                fresh_samples.append(
                    SemgrepSample(
                        code_raw=sample.raw_code,
                        code_analyzed=validation.code,
                        language=validation.expected_language,
                        precheck_error=(
                            validation.failure_reason if not validation.is_valid else None
                        ),
                        precheck_error_kind=validation.status,
                    )
                )
            analysis_start = time.perf_counter()
            fresh_semgrep = run_semgrep_batch_dir(fresh_samples)
            transient_kinds = {"timeout", "process", "json", "unexpected"}
            if any(result.error_kind in transient_kinds for result in fresh_semgrep):
                self._log("   ↻ Transient Semgrep failure — retrying the batch once")
                fresh_semgrep = run_semgrep_batch_dir(fresh_samples)
            if len(fresh_semgrep) != len(fresh_samples):
                self._record_evaluation_failure(
                    iter_id=iter_id,
                    stage="semgrep",
                    error_kind="result_count_mismatch",
                    message=(
                        f"submitted {len(fresh_samples)} samples, received "
                        f"{len(fresh_semgrep)} results"
                    ),
                )
                raise EvaluationInfrastructureError(
                    "Semgrep batch result count does not match submitted sample count"
                )
            scanned_count = sum(
                sample.precheck_error is None for sample in fresh_samples
            )
            per_scanned_sample_ms = (
                ((time.perf_counter() - analysis_start) * 1000) / max(scanned_count, 1)
            )
            for i, sample_input, sres in zip(fresh_indices, fresh_samples, fresh_semgrep):
                if sres.is_system_error:
                    self._record_evaluation_failure(
                        iter_id=iter_id,
                        stage="semgrep",
                        error_kind=sres.error_kind or "unknown",
                        message=sres.error or "unknown Semgrep error",
                        test_case_id=str(
                            generated[i].prompt.metadata.get("test_case_id", f"case_{i}")
                        ),
                    )
                    raise EvaluationInfrastructureError(
                        f"Semgrep evaluator failure ({sres.error_kind}): {sres.error}"
                    )
                semgrep_results[i] = sres
                analysis_latency_per_sample[i] = (
                    0.0 if sample_input.precheck_error is not None else per_scanned_sample_ms
                )
                if cache_enabled and cache_keys[i] is not None:
                    self._eval_cache[cache_keys[i]] = {  # type: ignore[index]
                        "code": generated[i].raw_code,
                        "gen_latency_ms": generated[i].generation_latency_ms,
                        "finish_reason": generated[i].finish_reason,
                        "semgrep_result": sres,
                        "analysis_latency_ms": analysis_latency_per_sample[i],
                    }
        else:
            self._log(f"   ⚡ Semgrep: all {len(generated)} samples reused from cache — skipping batch")

        # ---- Phase 3: fitness + per-prompt records
        results: list[EvaluationResult] = []
        fitness_results: list[FitnessResult] = []
        tc_log_lines: dict[int, str] = {}
        intermediate_records: list[dict] = []

        for idx, (semgrep_result, sample) in enumerate(zip(semgrep_results, generated)):
            if semgrep_result is None:
                raise EvaluationInfrastructureError(f"Missing Semgrep result for prompt index {idx}")
            if semgrep_result.is_system_error:
                self._record_evaluation_failure(
                    iter_id=iter_id,
                    stage="semgrep_cache",
                    error_kind=semgrep_result.error_kind or "unknown",
                    message=semgrep_result.error or "unknown cached Semgrep error",
                    test_case_id=str(sample.prompt.metadata.get("test_case_id", f"case_{idx}")),
                )
                raise EvaluationInfrastructureError(
                    f"Semgrep evaluator failure ({semgrep_result.error_kind}): {semgrep_result.error}"
                )
            validation = sample.validation
            if validation is None:
                raise RuntimeError(f"Missing output validation for prompt index {idx}")
            test_prompt = sample.prompt
            pwr = sample.prompt_with_rules
            tc_id = str(test_prompt.metadata.get("test_case_id", f"case_{idx}"))

            if semgrep_result.error_kind in {"target_parse", "target_analysis"} and validation.is_valid:
                validation.status = (
                    "semgrep_parse_error"
                    if semgrep_result.error_kind == "target_parse"
                    else "semgrep_target_error"
                )
                validation.failure_reason = semgrep_result.error

            if validation.is_valid and semgrep_result.error is None:
                fitness = calculate_fitness(semgrep_result)
            else:
                if is_baseline:
                    message = (
                        f"Baseline TC#{tc_id} failed during Semgrep analysis: "
                        f"{semgrep_result.error or validation.failure_reason}"
                    )
                    self._record_evaluation_failure(
                        iter_id=iter_id,
                        stage="baseline_semgrep",
                        error_kind=semgrep_result.error_kind or validation.status,
                        message=message,
                        test_case_id=tc_id,
                        details={
                            "finish_reason": sample.finish_reason,
                            "input_tokens": sample.input_tokens,
                            "output_tokens": sample.output_tokens,
                            "expected_language": validation.expected_language,
                            "detected_language": validation.detected_language,
                            "generated_code": sample.raw_code,
                            "analyzed_code_sha256": hashlib.sha256(
                                validation.code.encode("utf-8")
                            ).hexdigest(),
                            "partial_findings": [
                                {
                                    "check_id": finding.check_id,
                                    "severity": finding.severity,
                                    "line": finding.line,
                                }
                                for finding in semgrep_result.findings
                            ],
                        },
                    )
                    raise BaselineOutputError(
                        message
                    )
                baseline_for_imputation = self._baseline_fitness_per_case.get(tc_id)
                if baseline_for_imputation is None:
                    raise RuntimeError(f"Missing baseline fitness for TC#{tc_id}")
                fitness = deepcopy(baseline_for_imputation)
                fitness.score_source = "baseline_imputed"
                fitness.analysis_status = validation.status
                fitness.observed_raw_count = None
                fitness.observed_weighted_score = None
                observed_check_ids: list[str] = []
                if semgrep_result.error_kind in {"target_parse", "target_analysis"}:
                    observed_result = deepcopy(semgrep_result)
                    observed_result.error = None
                    observed_result.error_kind = None
                    observed = calculate_fitness(observed_result)
                    fitness.observed_raw_count = observed.raw_count
                    fitness.observed_weighted_score = observed.weighted_score
                    observed_check_ids = observed.details.get("check_ids", [])
                fitness.details = deepcopy(fitness.details)
                fitness.details["imputation"] = {
                    "reason": validation.failure_reason or semgrep_result.error,
                    "status": validation.status,
                    "source": "prompt_baseline",
                }
                fitness.details["observed_check_ids"] = observed_check_ids

            baseline = self._baseline_fitness_per_case.get(tc_id)
            baseline_raw = fitness.raw_count if baseline is None else baseline.raw_count
            baseline_weighted = (
                fitness.weighted_score if baseline is None else baseline.weighted_score
            )
            direction = 1.0 if self.config.objective_direction == "minimize" else -1.0
            fitness.raw_reduction = direction * float(baseline_raw - fitness.raw_count)
            fitness.weighted_reduction = direction * float(
                baseline_weighted - fitness.weighted_score
            )

            if is_baseline:
                self._baseline_fitness_per_case[tc_id] = deepcopy(fitness)

            fitness_results.append(fitness)
            eval_result = EvaluationResult(
                prompt=test_prompt,
                generated_code=sample.raw_code,
                fitness=fitness,
                generation_latency_ms=sample.generation_latency_ms,
                analysis_latency_ms=analysis_latency_per_sample[idx],
                input_tokens=sample.input_tokens,
                output_tokens=sample.output_tokens,
                finish_reason=sample.finish_reason,
                validation=validation,
            )
            results.append(eval_result)

            record = self._build_chromosome_prompt_record(
                eval_result, idx, iter_id, pwr, chromo,
                eval_cache_hit=cache_hit_flags[idx],
            )
            if record is not None:
                intermediate_records.append(record)

            if fitness.raw_reduction is not None:
                tc_log_lines[idx] = (
                    f"       → TC#{tc_id}: Vulns={fitness.raw_count} "
                    f"Weighted={fitness.weighted_score:.3f}, "
                    f"raw_reduction={fitness.raw_reduction:+.3f}, "
                    f"status={fitness.analysis_status}"
                )
            else:
                tc_log_lines[idx] = (
                    f"       → TC#{tc_id}: Score={fitness.weighted_score:.3f}, "
                    f"Vulns={fitness.raw_count}"
                )

        fresh_set = set(fresh_indices)
        for idx in fresh_indices:
            self._log(tc_log_lines[idx])
        reused_idx = [i for i in range(len(generated)) if i not in fresh_set]
        if reused_idx:
            reused_vulns = sum(fitness_results[i].raw_count for i in reused_idx)
            reused_vuln_prompts = sum(1 for i in reused_idx if fitness_results[i].raw_count > 0)
            self._log(
                f"   ♻️  {len(reused_idx)} prompts reused from cache — "
                f"vuln_prompts={reused_vuln_prompts}, vulns={reused_vulns}"
            )

        # Affected-prompt coverage is reported but is not an objective.
        affected_indices = [
            i for i, pwr in enumerate(prompts_with_rules)
            if (mutated & set(pwr.rule_ids))
            or any(chromo.order_priority.get(r, 0) for r in pwr.rule_ids)
        ]
        aggregated = aggregate_fitness(
            fitness_results,
            num_prompts_affected=len(affected_indices),
        )
        # Chromosome-level conservative objectives (pure functions of the
        # chromosome, independent of the per-prompt eval): f3 parsimony = # mutated
        # rules; f2 rule_fidelity = mean SBERT of mutated rules vs originals (1.0
        # if none).
        aggregated.parsimony = len(mutated)
        aggregated.rule_fidelity = self._chromosome_fidelity(chromo, space)

        # ---- Per-iteration metric sweep: proportions + movement at a glance --
        cur_vulns = sum(fr.raw_count for fr in fitness_results)
        cur_vuln_prompts = sum(1 for fr in fitness_results if fr.raw_count > 0)
        base = self._baseline_fitness_per_case
        if not is_baseline and base:
            base_vulns = 0
            base_vuln_prompts = 0
            for i in range(len(fitness_results)):
                tc = str(generated[i].prompt.metadata.get("test_case_id", ""))
                b = base.get(tc)
                if b is not None:
                    base_vulns += b.raw_count
                    base_vuln_prompts += 1 if b.raw_count > 0 else 0
            # Raw component metrics with explicit labels. The archive objectives
            # (f1/f2/f3, conservative set) are logged on the "archive add" line
            # in the runner.
            self._log(
                f"   📊 vuln_prompts={cur_vuln_prompts}/{len(fitness_results)} "
                f"(Δ{cur_vuln_prompts - base_vuln_prompts:+d}) | "
                f"vulns={cur_vulns} (Δ{cur_vulns - base_vulns:+d}) | "
                f"f1_raw_reduction={aggregated.total_raw_reduction:+.2f} "
                f"weighted_reduction={aggregated.total_weighted_reduction:+.2f} "
                f"invalid={aggregated.num_invalid_prompts} "
                f"fidelity={aggregated.rule_fidelity:.3f} pars={aggregated.parsimony}"
            )
        else:
            self._log(
                f"   📊 baseline: vuln_prompts={cur_vuln_prompts}/{len(fitness_results)} | "
                f"vulns={cur_vulns}"
            )

        if intermediate_records:
            self._save_intermediate_iter_jsonl(iter_id, intermediate_records)

        n_rerun = len(fresh_indices)
        n_reused = len(generated) - n_rerun
        return aggregated, results, n_reused, n_rerun

    def _build_chromosome_prompt_record(
        self,
        result: EvaluationResult,
        index: int,
        iter_id: str,
        pwr: "PromptWithRules",  # type: ignore
        chromo: RuleSetChromosome,
        eval_cache_hit: bool | None = None,
    ) -> dict | None:
        """One per-prompt evaluation record for intermediate/{iter_id}.jsonl.

        ``rules_used`` now describes the whole chromosome as it applies to this
        prompt: the mutated genes, this prompt's render order, whether the prompt
        was affected, and the chromosome id (links to the archive snapshot).
        """
        if not self.config.output_dir:
            return None

        mutated = sorted(chromo.mutated_rule_ids())
        render_order = chromo.render_order(pwr.rule_ids)
        prompt_affected = bool(set(pwr.rule_ids) & set(mutated)) or any(
            chromo.order_priority.get(r, 0) for r in pwr.rule_ids
        )
        return {
            "iter_id": iter_id,
            "index": index,
            "test_case_id": result.prompt.metadata.get("test_case_id", f"case_{index}"),
            "analysis_language": result.prompt.language,
            "cwe_id": result.prompt.cwe_id,
            "rules_used": {
                "original_rule_ids": list(pwr.rule_ids),
                "mutated_rule_ids": mutated,
                "render_order": render_order,
                "prompt_affected": prompt_affected,
                "chromosome_id": chromo.cid,
            },
            "fitness": {
                "raw_count": result.fitness.raw_count,
                "weighted_score": result.fitness.weighted_score,
                "raw_reduction": result.fitness.raw_reduction,
                "weighted_reduction": result.fitness.weighted_reduction,
                "unique_rules": result.fitness.unique_rules,
                "error_count": result.fitness.error_count,
                "warning_count": result.fitness.warning_count,
                "check_ids": result.fitness.details.get("check_ids", []),
                "score_source": result.fitness.score_source,
                "analysis_status": result.fitness.analysis_status,
                "observed_raw_count": result.fitness.observed_raw_count,
                "observed_weighted_score": result.fitness.observed_weighted_score,
                "observed_check_ids": result.fitness.details.get("observed_check_ids", []),
                "imputation": result.fitness.details.get("imputation"),
            },
            "output_validation": (
                {
                    "status": result.validation.status,
                    "failure_reason": result.validation.failure_reason,
                    "syntax_error": result.validation.syntax_error,
                    "syntax_validation_method": result.validation.syntax_validation_method,
                    "finish_reason": result.validation.finish_reason,
                    "expected_language": result.validation.expected_language,
                    "detected_language": result.validation.detected_language,
                    "fence_languages": result.validation.fence_languages,
                    "ignored_supplementary_languages": (
                        result.validation.ignored_supplementary_languages
                    ),
                    "has_fences": result.validation.has_fences,
                    "outside_text_present": result.validation.outside_text_present,
                }
                if result.validation is not None else None
            ),
            "generation_latency_ms": result.generation_latency_ms,
            "analysis_latency_ms": result.analysis_latency_ms,
            "input_tokens": result.input_tokens,
            "output_tokens": result.output_tokens,
            "finish_reason": result.finish_reason,
            "eval_cache_hit": eval_cache_hit,
            "llm_calls_so_far": self._total_llm_calls,
            "input_tokens_so_far": self._total_input_tokens,
            "output_tokens_so_far": self._total_output_tokens,
            "generated_code": result.generated_code,
            "analyzed_code_sha256": (
                hashlib.sha256(result.validation.code.encode("utf-8")).hexdigest()
                if result.validation is not None else None
            ),
        }

    def _save_evaluation_manifest(self, baseline_results: list[EvaluationResult]) -> None:
        """Persist the exact task/language contract accepted at baseline."""
        if not self.config.output_dir:
            return
        rows = []
        for result in baseline_results:
            tc_id = str(result.prompt.metadata.get("test_case_id"))
            rows.append({
                "test_case_id": tc_id,
                "analysis_language": self._expected_language_per_case.get(tc_id),
                "baseline_status": (
                    result.validation.status if result.validation is not None else "unknown"
                ),
            })
        payload = {
            "schema_version": 1,
            "prompts": rows,
        }
        path = Path(self.config.output_dir) / "evaluation_manifest.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    def _save_results(self, result: SearchResult) -> None:
        """Save results to output directory."""
        output_dir = self.config.output_dir
        if not output_dir:
            return

        output_dir.mkdir(parents=True, exist_ok=True)
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

        # Save summary
        summary = {
            "timestamp": timestamp,
            "llm_provider": self.llm.provider_name,
            "llm_model": self.llm.model_name,
            "mutators": self.pool.mutator_names,
            "max_iterations": self.config.max_iterations,
            "num_iterations_run": len(result.iterations),
            "primary_f1_metric": "raw_semgrep_finding_count",
            "original_raw_findings": result.original_fitness.total_raw_count,
            "best_raw_findings": result.best_fitness.total_raw_count,
            "raw_findings_reduction": (
                result.original_fitness.total_raw_count - result.best_fitness.total_raw_count
            ),
            "original_weighted_score": result.original_fitness.total_weighted_score,
            "best_weighted_score": result.best_fitness.total_weighted_score,
            "weighted_score_reduction": (
                result.original_fitness.total_weighted_score
                - result.best_fitness.total_weighted_score
            ),
            "best_num_invalid_prompts": result.best_fitness.num_invalid_prompts,
            "best_failure_counts": result.best_fitness.failure_counts,
            "total_time_seconds": result.total_time_seconds,
            "total_llm_calls": result.total_llm_calls,
            "total_input_tokens": result.total_input_tokens,
            "total_output_tokens": result.total_output_tokens,
        }
        if result.pool_arm_stats:
            summary["pool_arm_stats"] = result.pool_arm_stats
        if result.eval_cache_stats:
            summary["eval_cache_stats"] = result.eval_cache_stats
        # Full run configuration lives in run_config.json (no duplication here).
        summary["run_config_ref"] = "see run_config.json"

        # Filename kept from the output-schema spec ("hillclimb" is historical)
        # so run-collection tooling keeps matching hillclimb_summary_*.json.
        summary_path = output_dir / f"hillclimb_summary_{timestamp}.json"
        with open(summary_path, "w") as f:
            json.dump(summary, f, indent=2)

        # The per-rule view (hillclimb_per_rule_*.json) and per_prompt_rules_results
        # are intentionally NOT written — both are fully derivable from
        # iterations.jsonl + archive_snapshots/ + intermediate/ by the analysis
        # layer (output-schema spec Files 7/8).

        self._log(f"📁 Results saved to {output_dir}")
